#!/usr/bin/env node
/* ==========================================================================
   build-lang-data.mjs — lang/*.json -> assets/js/lang-data.js  (+ sitemap.xml)

   Usage
     node scripts/build-lang-data.mjs
     node scripts/build-lang-data.mjs --sync-detail <id>

   --sync-detail <id>
     Copies every en.json `detail_<id>_*` value into kr.json and jp.json where
     the key is missing (detail bodies are English-only, 03 §7) and rewrites
     both files following en.json's key order. Run it right after adding a new
     detail page, then run the plain build.

   Output is deterministic: key order follows the JSON files, indentation is
   two spaces, and the file always ends with a newline. scripts/check.mjs
   compares the committed lang-data.js byte for byte against a fresh build.
   ========================================================================== */
import { readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LANGS = ["en", "kr", "jp"];
const DOMAIN_FALLBACK = "https://junon-lee.pages.dev";
const HEADER = [
  "/* GENERATED by scripts/build-lang-data.mjs. Do not edit. */",
  "/* en is complete. kr and jp hold only the keys whose value differs from en;",
  "   lang.js resolves current language -> en -> the text already in the HTML.",
  "   lang/kr.json and lang/jp.json on disk stay complete files. */"
].join("\n");

const p = (...s) => join(ROOT, ...s);
const readJson = (f) => JSON.parse(readFileSync(f, "utf8"));

/* ---------- lang-data.js --------------------------------------------------- */

/* kr and jp are delta-encoded against en: a key is emitted only when its value
   differs. That keeps the synchronously loaded bundle small (06 §4 targets
   < 60 KB) without changing what lang.js resolves, because its lookup order is
   already current language -> en -> HTML fallback. */
function delta(base, other) {
  const out = {};
  for (const k of Object.keys(base)) {
    if (k in other && other[k] !== base[k]) out[k] = other[k];
  }
  for (const k of Object.keys(other)) {          /* keys en does not have */
    if (!(k in base)) out[k] = other[k];
  }
  return out;
}

export function buildLangData() {
  const full = {};
  for (const l of LANGS) full[l] = readJson(p("lang", `${l}.json`));
  const data = { en: full.en };
  for (const l of LANGS) if (l !== "en") data[l] = delta(full.en, full[l]);
  return `${HEADER}\nwindow.TRANSLATION_DATA = ${JSON.stringify(data, null, 2)};\n`;
}

/* ---------- works-data.js (sitemap + sync helpers) ------------------------- */

export function loadWorks() {
  const file = p("assets", "js", "works-data.js");
  if (!existsSync(file)) return { works: [], site: {} };
  const win = {};
  try {
    new Function("window", readFileSync(file, "utf8"))(win);
  } catch {
    return { works: [], site: {} };
  }
  return { works: Array.isArray(win.WORKS) ? win.WORKS : [], site: win.SITE || {} };
}

const STATIC_PAGES = [
  "index.html", "portfolio.html", "resume.html", "contact.html"
];

export function sitePages() {
  const { works } = loadWorks();
  const detail = works.length
    ? works.map((w) => w.href || `${w.type}_${w.id}.html`)
    : [
        "project_ebpf.html", "project_rowscope.html", "project_can.html",
        "project_5g_oran.html", "project_opencl.html",
        "research_dynamic_moh.html", "research_pim_accel.html"
      ];
  return [...STATIC_PAGES, ...detail];         /* 11 pages, 404.html excluded */
}

export function buildSitemap() {
  const { site } = loadWorks();
  const domain = (site.domain || DOMAIN_FALLBACK).replace(/\/$/, "");
  const lines = ['<?xml version="1.0" encoding="UTF-8"?>',
                 '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'];
  for (const page of sitePages()) {
    const loc = page === "index.html" ? `${domain}/` : `${domain}/${page}`;
    const file = p(page);
    const mod = existsSync(file)
      ? statSync(file).mtime.toISOString().slice(0, 10)
      : null;
    lines.push("  <url>");
    lines.push(`    <loc>${loc}</loc>`);
    if (mod) lines.push(`    <lastmod>${mod}</lastmod>`);
    lines.push("  </url>");
  }
  lines.push("</urlset>", "");
  return lines.join("\n");
}

/* ---------- --sync-detail -------------------------------------------------- */

function syncDetail(id) {
  const en = readJson(p("lang", "en.json"));
  const prefix = `detail_${id}_`;
  const keys = Object.keys(en).filter((k) => k.startsWith(prefix));
  if (!keys.length) {
    console.error(`! no ${prefix}* keys in lang/en.json`);
    process.exitCode = 1;
    return;
  }
  for (const lang of ["kr", "jp"]) {
    const file = p("lang", `${lang}.json`);
    const cur = readJson(file);
    let added = 0;
    for (const k of keys) if (!(k in cur)) { cur[k] = en[k]; added++; }
    /* rewrite following en.json's order so the three files stay comparable */
    const out = {};
    for (const k of Object.keys(en)) if (k in cur) out[k] = cur[k];
    for (const k of Object.keys(cur)) if (!(k in out)) out[k] = cur[k];
    writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`);
    console.log(`  lang/${lang}.json  +${added} key(s) for ${prefix}*`);
  }
}

/* ---------- main ----------------------------------------------------------- */

function main() {
  const args = process.argv.slice(2);
  const i = args.indexOf("--sync-detail");
  if (i !== -1) {
    const id = args[i + 1];
    if (!id) { console.error("! --sync-detail needs a work id"); process.exit(1); }
    syncDetail(id);
  }

  const langData = buildLangData();
  writeFileSync(p("assets", "js", "lang-data.js"), langData);
  console.log(`  assets/js/lang-data.js  ${(langData.length / 1024).toFixed(1)} KB`);

  const sitemap = buildSitemap();
  writeFileSync(p("sitemap.xml"), sitemap);
  console.log(`  sitemap.xml             ${sitePages().length} pages`);
}

if (process.argv[1] && process.argv[1].endsWith("build-lang-data.mjs")) main();
